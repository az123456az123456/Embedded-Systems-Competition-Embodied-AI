#!/usr/bin/env python3
"""PC regression: run the REAL static ARM64 receiver under BSP QEMU.
Requires the replay verified/generated by FPGA tests/run.py.
"""
from pathlib import Path
import argparse, hashlib, json, struct, subprocess, tempfile

BASE = Path(__file__).resolve().parents[1]
ROOT = BASE.parents[1]
ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument('--qemu', type=Path)
ap.add_argument('--replay', type=Path, default=ROOT/'fpga/raw_calibration_standalone/build/wire.rawcap')
a = ap.parse_args()
qemu = a.qemu or next(ROOT.glob('bsp_r4/*/sdk/yy3588_sdk-bsp/device/rockchip/common/tools/x86_64/qemu-aarch64-static'))
binary = BASE/'bin/rawcap.aarch64'
records = []
with a.replay.open('rb') as f:
    while h := f.read(4):
        assert len(h) == 4
        n = struct.unpack('<I', h)[0]
        b = f.read(n)
        assert len(b) == n
        records.append(b)
def row(b): return int.from_bytes(b[42:44], 'little')
meta = next(b for b in records if row(b) == 65535)
pixels = [b for b in records if row(b) != 65535]
assert len(pixels) == 2160
# Use a profile first; the real wire test deliberately starts streaming first.
normal = [meta] + pixels
cases = []
with tempfile.TemporaryDirectory(prefix='rawcal-arm64-tests-') as d:
    temp = Path(d)
    serial = 0
    def run(name, packets=normal, args=None, ok=True, error=None, dest=None):
        global serial
        serial += 1
        replay = temp/f'{serial}.rawcap'
        replay.write_bytes(b''.join(struct.pack('<I', len(b)) + b for b in packets))
        output = dest or temp/f'out-{serial}'
        cmd = [str(qemu.resolve()), str(binary), '--replay', str(replay)]
        cmd += args if args is not None else ['capture', '--kind', 'flat', '--out-dir', str(output), '--frames', '2', '--discard', '0']
        p = subprocess.run(cmd, text=True, capture_output=True, timeout=30)
        assert (p.returncode == 0) == ok, (name, p.returncode, p.stdout, p.stderr)
        if error: assert error in p.stderr, (name, p.stderr)
        if not ok and dest is None:
            assert not list(output.glob('*.raw')) and not list(output.glob('*.part'))
            assert not (output/'.capture.lock').exists()
        cases.append({'case': name, 'result': 'PASS', 'exit': p.returncode})
        print('PASS', name)
        return output, p
    out, _ = run('ARM64 complete two-frame exact capture')
    for eye in (0, 1):
        golden = b''.join(bytes(((x+3*y+7*f) if eye == 0 else (2*x+5*y+11*f+40)) & 255 for x in range(960)) for f in range(2) for y in range(1080))
        assert (out/f'cam{eye}-flat.raw').read_bytes() == golden
    profile = json.loads((out/'profile-flat.json').read_text())
    assert profile['frames_per_eye'] == 2 and profile['bytes_per_eye'] == 2073600
    run('ARM64 register readback info', args=['info'])
    run('ARM64 frame statistics', args=['stats', '--frames', '2', '--discard', '0'])
    run('dark same profile accepted', args=['capture','--kind','dark','--out-dir',str(out),'--frames','2','--discard','0'], dest=out)
    run('dark requires prior flat', args=['capture','--kind','dark','--out-dir',str(temp/'missing')], ok=False, error='requires flat profile')
    run('refuse overwrite', dest=out, ok=False, error='already exists')
    bad = bytearray(meta); bad[44+24+2] = 0
    run('manual exposure lock missing', [bytes(bad)]+pixels, ok=False, error='does not confirm')
    bad = bytearray(meta); bad[44+5] = 4; bad[44+17] = 1
    run('camera NACK terminal error', [bytes(bad)]+pixels, ok=False, error='camera setup failed')
    bad = bytearray(meta); bad[44+8] ^= 1
    run('wrong dimensions', [bytes(bad)]+pixels, ok=False, error='Wrong RAW dimensions')
    bad = bytearray(meta); bad[44+24+28] ^= 1
    run('readback crop differs', [bytes(bad)]+pixels, ok=False, error='crop size')
    bad = bytearray(meta); bad[44+24+4] ^= 1
    run('profile drift during capture', [meta]+pixels[:100]+[bytes(bad)]+pixels[100:], ok=False, error='profile changed')
    run('dark different flat profile rejected', [bytes(bad)]+pixels, args=['capture','--kind','dark','--out-dir',str(temp/'different'),'--reference',str(out/'profile-flat.json'),'--frames','2','--discard','0'], ok=False, error='settings differ')
    run('missing row never commits', [meta]+[b for b in pixels if row(b)!=100], ok=False, error='Replay ended')
    swapped = pixels.copy(); swapped[1],swapped[2]=swapped[2],swapped[1]
    run('row reorder never commits incomplete frame', [meta]+swapped, ok=False, error='Replay ended')
    run('no locked metadata', pixels, ok=False, error='Replay ended')
    bad = bytearray(meta); bad[44+5] = 0
    run('startup metadata waits until lock', [bytes(bad)]+normal)
    # Damage IP checksum in one row in each frame. Parser must discard it.
    damaged = []
    for b in pixels:
        c = bytearray(b)
        if row(b)==123: c[24] ^= 1
        damaged.append(bytes(c))
    run('corrupt IP headers rejected', [meta]+damaged, ok=False, error='Replay ended')
    # A receiver sees unrelated FPGA/host traffic on the same AF_PACKET socket.
    run('unrelated packets ignored', [bytes(60)]+normal)
    lock = temp/'busy'; lock.mkdir(); (lock/'.capture.lock').mkdir()
    run('concurrent output directory protected', dest=lock, ok=False, error='directory is busy')
report = {'result':'PASS','architecture':'actual static ARM64 binary under BSP QEMU','binary_sha256':hashlib.sha256(binary.read_bytes()).hexdigest(),'replay_sha256':hashlib.sha256(a.replay.read_bytes()).hexdigest(),'cases':cases,'hardware_tested':False}
(BASE/'reports/receiver-regression.json').write_text(json.dumps(report,indent=2)+'\n')
