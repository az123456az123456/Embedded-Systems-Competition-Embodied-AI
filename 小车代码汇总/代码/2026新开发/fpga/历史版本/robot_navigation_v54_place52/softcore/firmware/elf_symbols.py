#!/usr/bin/env python3
"""Export testbench addresses from this exact firmware ELF, never guessed offsets."""
import argparse
from pathlib import Path
import subprocess

SYMBOLS = {
    "__bss_start": "NAV_FW_BSS_START",
    "__bss_end": "NAV_FW_BSS_END",
    "__stack_bottom": "NAV_FW_STACK_BOTTOM",
    "__stack_top": "NAV_FW_STACK_TOP",
    "selftest_passes": "NAV_FW_SELFTEST_PASSES",
    "observed_imu_words": "NAV_FW_OBSERVED_IMU",
    "observed_motor_words": "NAV_FW_OBSERVED_MOTOR",
    "layered_state": "NAV_FW_LAYERED_STATE",
    "navigation_runtime": "NAV_FW_RUNTIME",
    "server": "NAV_FW_SERVER",
    "control_service_calls": "NAV_FW_SERVICE_CALLS",
    "control_service_max_gap_cycles": "NAV_FW_SERVICE_MAX_GAP",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nm", required=True)
    parser.add_argument("elf", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    result = subprocess.run([args.nm, "--defined-only", str(args.elf)],
                            check=True, capture_output=True, text=True)
    found = {}
    for line in result.stdout.splitlines():
        fields = line.split()
        if len(fields) == 3 and fields[2] in SYMBOLS:
            found[fields[2]] = int(fields[0], 16)
    missing = SYMBOLS.keys() - found.keys()
    if missing:
        parser.error(f"missing ELF symbols: {sorted(missing)}")
    args.output.write_text("// Generated by elf_symbols.py from firmware.elf.\n" +
                           "".join(f"`define {define} 32'h{found[name]:08x}\n"
                                   for name, define in SYMBOLS.items()))


if __name__ == "__main__":
    main()
